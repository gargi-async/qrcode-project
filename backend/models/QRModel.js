const mongoose = require('mongoose');

/**
 * QR Schema Definition
 * Defines the structure of documents saved in MongoDB for ScanPulse.
 */
const qrSchema = new mongoose.Schema({
    originalUrl: { 
        type: String, 
        required: true, 
        trim: true 
    },
    shortCode: { 
        type: String, 
        required: true, 
        unique: true 
    },
    qrDataUrl: { 
        type: String, 
        required: true // Stores the base64 image string generated by the qrcode library
    },
    fgColor: { 
        type: String, 
        default: '#0f172a' 
    },
    bgColor: { 
        type: String, 
        default: '#ffffff' 
    },
    category: { 
        type: String, 
        default: 'General' 
    },
    scanCount: { 
        type: Number, 
        default: 0 // Counter for tracking scans
    },
    createdAt: { 
        type: Date, 
        default: Date.now 
    }
});

module.exports = mongoose.model('QRRecord', qrSchema);